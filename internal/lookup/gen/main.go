// Command gen writes zz_generated_cloudformation.go. It maps the ARN formats of
// taggable AWS resources to the CloudFormation types that can have them.
//
// AWS doesn't publish this mapping, so gen derives it from two sources:
//
//   - The CloudFormation resource schemas. Each taggable type lists the IAM
//     actions its handlers need, for example rds:DeleteDBInstance.
//   - The Service Authorization Reference. Each IAM action lists the resource
//     types it acts on, and each resource type has an ARN format, for example
//     arn:${Partition}:rds:${Region}:${Account}:db:${DbInstanceName}.
//
// For every CloudFormation type, gen picks the IAM resource type that its
// handlers act on most and whose name is most like the CloudFormation type
// name.
package main

import (
	"archive/zip"
	"bytes"
	"cmp"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"sync"
	"time"
)

const (
	schemaURL           = "https://schema.cloudformation.us-east-1.amazonaws.com/CloudformationSchema.zip"
	serviceReferenceURL = "https://servicereference.us-east-1.amazonaws.com/"
	parallelDownloads   = 16
)

type schema struct {
	TypeName string          `json:"typeName"`
	Tagging  json.RawMessage `json:"tagging"`
	Handlers map[string]struct {
		Permissions []string `json:"permissions"`
	} `json:"handlers"`
}

type tagging struct {
	Taggable bool `json:"taggable"`
}

// service is a service in the Service Authorization Reference.
//
//nolint:tagliatelle // The reference uses capitalised keys.
type service struct {
	Name    string `json:"Name"`
	Actions []struct {
		Name      string `json:"Name"`
		Resources []struct {
			Name string `json:"Name"`
		} `json:"Resources"`
	} `json:"Actions"`
	Resources []struct {
		Name       string   `json:"Name"`
		ARNFormats []string `json:"ARNFormats"`
	} `json:"Resources"`
}

// iamResource is a resource type in the Service Authorization Reference.
type iamResource struct {
	Service, Name string
}

type candidate struct {
	typeName string
	nameSim  float64
	nsSim    float64
}

func main() {
	out := flag.String("out", "zz_generated_cloudformation.go", "file to write")
	flag.Parse()

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	err := run(ctx, *out)
	cancel()
	if err != nil {
		log.Fatal(err)
	}
}

func run(ctx context.Context, out string) error {
	schemas, err := schemas(ctx)
	if err != nil {
		return err
	}
	services, err := services(ctx)
	if err != nil {
		return err
	}

	actions := map[string][]iamResource{}
	formats := map[iamResource][]string{}
	for _, s := range services {
		svc := strings.ToLower(s.Name)
		for _, r := range s.Resources {
			formats[iamResource{svc, r.Name}] = r.ARNFormats
		}
		for _, a := range s.Actions {
			key := strings.ToLower(svc + ":" + a.Name)
			for _, r := range a.Resources {
				actions[key] = append(actions[key], iamResource{svc, r.Name})
			}
		}
	}

	byResource := map[iamResource][]candidate{}
	mapped := 0
	for _, s := range schemas {
		rs, c, ok := match(s, actions)
		if !ok {
			continue
		}
		for _, r := range rs {
			byResource[r] = append(byResource[r], c)
		}
		mapped++
	}

	byFormat := map[string][]candidate{}
	for r, cs := range byResource {
		for _, f := range formats[r] {
			if strings.HasPrefix(f, "arn:") {
				byFormat[f] = append(byFormat[f], cs...)
			}
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package lookup\n\n")
	fmt.Fprintf(&b, "// arnFormats maps the ARN formats of taggable AWS resources to the\n")
	fmt.Fprintf(&b, "// CloudFormation types that can have them, best match first.\n")
	fmt.Fprintf(&b, "var arnFormats = []arnFormat{\n")
	for _, f := range slices.Sorted(maps.Keys(byFormat)) {
		cs := byFormat[f]
		slices.SortFunc(cs, func(a, b candidate) int {
			return cmp.Or(cmp.Compare(b.nameSim, a.nameSim), cmp.Compare(b.nsSim, a.nsSim), strings.Compare(a.typeName, b.typeName))
		})
		cs = slices.CompactFunc(cs, func(a, b candidate) bool { return a.typeName == b.typeName })
		types := make([]string, 0, len(cs))
		for _, c := range cs {
			types = append(types, fmt.Sprintf("%q", c.typeName))
		}
		fmt.Fprintf(&b, "\t{%q, []string{%s}},\n", f, strings.Join(types, ", "))
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("cannot format generated code: %w", err)
	}
	if err := os.WriteFile(out, src, 0o600); err != nil {
		return err
	}

	log.Printf("mapped %d of %d taggable CloudFormation types to %d ARN formats", mapped, len(schemas), len(byFormat))
	return nil
}

// match returns the IAM resource types of a CloudFormation type. That is
// usually one, but some services split a resource type into variants, such as
// loadbalancer/app/ and loadbalancer/net/ next to loadbalancer.
func match(s schema, actions map[string][]iamResource) ([]iamResource, candidate, bool) {
	parts := strings.Split(s.TypeName, "::")
	ns, name := parts[1], parts[2]

	home := pick(s.Handlers["delete"].Permissions, name, ns, "Delete", "Remove", "Deregister", "Terminate", "Disassociate", "Detach", "Release", "Cancel", "Stop")
	if home == "" {
		home = pick(s.Handlers["read"].Permissions, name, ns, "Describe", "Get", "List")
	}
	if home == "" {
		if p := s.Handlers["read"].Permissions; len(p) > 0 {
			home, _, _ = strings.Cut(strings.ToLower(p[0]), ":")
		}
	}

	freq := map[iamResource]float64{}
	for _, h := range []struct {
		name   string
		weight float64
	}{{"delete", 3}, {"read", 2}, {"update", 1}, {"create", 1}} {
		for _, p := range s.Handlers[h.name].Permissions {
			rs := actions[strings.ToLower(p)]
			if len(rs) == 0 {
				continue
			}
			_, act, _ := strings.Cut(p, ":")
			w := h.weight
			if strings.Contains(norm(act), norm(name)) {
				w *= 2
			}
			for _, r := range rs {
				if r.Service == home {
					freq[r] += w / float64(len(rs))
				}
			}
		}
	}
	if len(freq) == 0 {
		return nil, candidate{}, false
	}

	top := slices.Max(slices.Collect(maps.Values(freq)))
	var best iamResource
	bestScore := -1.0
	for _, r := range slices.SortedFunc(maps.Keys(freq), func(a, b iamResource) int {
		return cmp.Or(strings.Compare(a.Service, b.Service), strings.Compare(a.Name, b.Name))
	}) {
		if score := sim(name, r.Name)*2 + 4*freq[r]/top; score > bestScore {
			best, bestScore = r, score
		}
	}

	// A type whose handlers only act on another service's resources, such as
	// a KMS key or an IAM role, has no IAM resource type of its own.
	if sim(ns, best.Service) == 0 && sim(name, best.Name) < 6 {
		return nil, candidate{}, false
	}

	rs := []iamResource{best}
	for r := range freq {
		if r != best && strings.HasPrefix(r.Name, best.Name+"/") {
			rs = append(rs, r)
		}
	}

	return rs, candidate{typeName: s.TypeName, nameSim: sim(name, best.Name), nsSim: sim(ns, best.Service)}, true
}

// pick returns the service of the permission that most looks like the
// action for the CloudFormation type, for example rds:DeleteDBInstance.
func pick(perms []string, name, ns string, verbs ...string) string {
	best, bestScore := "", -1.0
	for i, p := range perms {
		svc, act, ok := strings.Cut(p, ":")
		if !ok {
			continue
		}
		for _, v := range verbs {
			if !strings.HasPrefix(act, v) {
				continue
			}
			if score := sim(name, strings.TrimPrefix(act, v))*10 + sim(ns, svc) - float64(i)*0.01; score > bestScore {
				best, bestScore = strings.ToLower(svc), score
			}
			break
		}
	}
	return best
}

var (
	nonAlnum   = regexp.MustCompile(`[^a-z0-9]+`)
	lowerUpper = regexp.MustCompile(`([a-z0-9])([A-Z])`)
	upperWord  = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
)

func norm(s string) string { return nonAlnum.ReplaceAllString(strings.ToLower(s), "") }

func tokens(s string) map[string]bool {
	s = lowerUpper.ReplaceAllString(s, "$1 $2")
	s = upperWord.ReplaceAllString(s, "$1 $2")
	t := map[string]bool{}
	for _, w := range nonAlnum.Split(strings.ToLower(s), -1) {
		if w != "" {
			t[w] = true
		}
	}
	return t
}

// sim scores how alike two names are, from 0 (nothing in common) to 10
// (equal apart from case and punctuation).
func sim(a, b string) float64 {
	na, nb := norm(a), norm(b)
	switch {
	case na == nb:
		return 10
	case strings.HasSuffix(na, nb) || strings.HasSuffix(nb, na):
		return 6
	}
	ta, tb := tokens(a), tokens(b)
	overlap := 0
	for w := range ta {
		if tb[w] {
			overlap++
		}
	}
	if overlap == 0 {
		return 0
	}
	return 3 * float64(overlap) / float64(max(len(ta), len(tb)))
}

// schemas returns the taggable AWS CloudFormation types that Cloud Control
// can read.
func schemas(ctx context.Context) ([]schema, error) {
	body, err := get(ctx, schemaURL)
	if err != nil {
		return nil, err
	}
	z, err := zip.NewReader(bytes.NewReader(body), int64(len(body)))
	if err != nil {
		return nil, fmt.Errorf("cannot open CloudFormation schemas: %w", err)
	}

	var out []schema
	for _, f := range z.File {
		if !strings.HasPrefix(f.Name, "aws-") || !strings.HasSuffix(f.Name, ".json") {
			continue
		}
		r, err := f.Open()
		if err != nil {
			return nil, err
		}
		var s schema
		err = json.NewDecoder(r).Decode(&s)
		_ = r.Close()
		if err != nil {
			return nil, fmt.Errorf("cannot parse %s: %w", f.Name, err)
		}

		var t tagging
		if json.Unmarshal(s.Tagging, &t) != nil || !t.Taggable {
			continue
		}
		if _, ok := s.Handlers["read"]; !ok || len(strings.Split(s.TypeName, "::")) != 3 {
			continue
		}
		out = append(out, s)
	}
	slices.SortFunc(out, func(a, b schema) int { return strings.Compare(a.TypeName, b.TypeName) })
	return out, nil
}

// services returns every service in the Service Authorization Reference.
func services(ctx context.Context) ([]service, error) {
	body, err := get(ctx, serviceReferenceURL)
	if err != nil {
		return nil, err
	}
	var index []struct {
		URL string `json:"url"`
	}
	if err := json.Unmarshal(body, &index); err != nil {
		return nil, fmt.Errorf("cannot parse the Service Authorization Reference index: %w", err)
	}

	out := make([]service, len(index))
	errs := make([]error, len(index))
	sem := make(chan struct{}, parallelDownloads)
	var wg sync.WaitGroup
	for i, s := range index {
		wg.Go(func() {
			sem <- struct{}{}
			defer func() { <-sem }()
			body, err := get(ctx, s.URL)
			if err == nil {
				err = json.Unmarshal(body, &out[i])
			}
			errs[i] = err
		})
	}
	wg.Wait()
	return out, errors.Join(errs...)
}

func get(ctx context.Context, url string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	rsp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer rsp.Body.Close() //nolint:errcheck // Read-only.
	if rsp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, rsp.Status)
	}
	return io.ReadAll(rsp.Body)
}
